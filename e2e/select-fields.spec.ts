import { expect, test } from '@playwright/test';
import { signupToBoard } from './helpers';

test('select menus use the theme, retain native keyboard behavior and work inside popovers and dialogs', async ({ browser }, info) => {
  const { page, account } = await signupToBoard(browser, { viewport: { width: 1440, height: 1000 } });
  const select = page.getByRole('combobox', { name: 'Group by', exact: true });
  expect(await select.evaluate(() => CSS.supports('appearance', 'base-select'))).toBe(true);
  await select.click();
  await expect(select).toHaveCSS('appearance', 'base-select');
  await expect(select.getByRole('option', { name: 'Due date', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('select-menu-light.png'), fullPage: true, animations: 'disabled', style: 'nextjs-portal { visibility: hidden; }' });
  await page.keyboard.press('Escape'); await expect(select).toBeFocused();
  await select.press('Space'); await page.keyboard.press('End'); await page.keyboard.press('Enter');
  await expect(select).toHaveValue('due'); await expect(page).toHaveURL(/group=due/);
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await select.click(); await expect(select.getByRole('option', { name: 'Due date', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('select-menu-dark.png'), fullPage: true, animations: 'disabled', style: 'nextjs-portal { visibility: hidden; }' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Filters', exact: true }).click();
  const filters = page.getByTestId('filter-panel'); const due = filters.getByLabel('Due date');
  await due.click(); await due.getByRole('option', { name: 'No due date', exact: true }).click();
  await expect(filters).toBeVisible(); await expect(due).toHaveValue('none');
  await filters.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Share', exact: true }).click();
  const share = page.getByRole('dialog', { name: 'Share project', exact: true });
  const access = share.getByLabel('New project access', { exact: true });
  await access.click(); await access.getByRole('option', { name: 'Project admin', exact: true }).click();
  await expect(share).toBeVisible(); await expect(access).toHaveValue('admin');
  await share.getByRole('button', { name: 'Close Share project' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await select.click();
  const option = select.getByRole('option', { name: 'Assignee', exact: true });
  await expect(option).toBeVisible();
  const box = (await option.boundingBox())!;
  expect(box.height).toBeGreaterThanOrEqual(44);
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: info.outputPath('select-menu-mobile.png'), fullPage: true, animations: 'disabled', style: 'nextjs-portal { visibility: hidden; }' });
  await page.keyboard.press('Escape');
  const workspaceId = new URL(account.boardUrl).pathname.split('/')[2]!;
  await page.goto(`/w/${workspaceId}/settings/members`);
  const role = page.getByRole('combobox', { name: 'Role', exact: true });
  await role.click(); await role.getByRole('option', { name: 'Admin', exact: true }).click();
  expect(await role.evaluate((node: HTMLSelectElement) => new FormData(node.form!).get('role'))).toBe('admin');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.context().close();
});
