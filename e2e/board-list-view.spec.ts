test('switching views releases the active drag snapshot and keeps new cards live', async ({ browser }) => {
  const { page } = await signupToBoard(browser, { viewport: { width: 1440, height: 1000 } });
  const todo = list(page, 'To do');
  await todo.getByTestId('add-card-end').click();
  await todo.getByLabel('Card title').fill('Review the first concept');
  await page.keyboard.press('Enter'); await page.keyboard.press('Escape');
  const card = todo.getByRole('button', { name: /Review the first concept/ });
  await card.focus(); await page.keyboard.press('Space');
  await expect(card).toHaveAttribute('aria-pressed', 'true');
  const views = page.getByRole('group', { name: 'Board view', exact: true });
  await views.getByRole('button', { name: 'List', exact: true }).click();
  await expect(todo.getByRole('link', { name: /Review the first concept/ })).toBeVisible();
  await expect(list(page, 'In progress').getByRole('link', { name: /Review the first concept/ })).toHaveCount(0);
  await todo.getByTestId('add-card-end').click();
  await todo.getByLabel('Card title').fill('Plan the next iteration'); await page.keyboard.press('Enter');
  await expect(todo.getByRole('link', { name: /Plan the next iteration/ })).toBeVisible();
  await views.getByRole('button', { name: 'Kanban', exact: true }).click();
  await expect(card).not.toHaveAttribute('aria-pressed', 'true');
  await expect(todo.getByRole('button', { name: /Plan the next iteration/ })).toBeVisible();
  await page.context().close();
});
